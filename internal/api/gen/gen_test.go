// TestGeneratedFilesUpToDate fails when rpc_gen.go or apitest/stub_gen.go
// no longer match local.go. Fix: go generate ./internal/api
func TestGeneratedFilesUpToDate(t *testing.T) {
	src, err := os.ReadFile(filepath.Join("..", "local.go"))
	require.NoError(t, err)
	rpc, stub, err := Generate(src)
	require.NoError(t, err)
	gotRPC, err := os.ReadFile(filepath.Join("..", "rpc_gen.go"))
	require.NoError(t, err)
	gotStub, err := os.ReadFile(filepath.Join("..", "apitest", "stub_gen.go"))
	require.NoError(t, err)
	require.Equal(t, string(rpc), string(gotRPC), "internal/api/rpc_gen.go is stale: run go generate ./internal/api")
	require.Equal(t, string(stub), string(gotStub), "internal/api/apitest/stub_gen.go is stale: run go generate ./internal/api")
}

func TestRunWritesFiles(t *testing.T) {
	dir := t.TempDir()
	rpc := filepath.Join(dir, "rpc_gen.go")
	stub := filepath.Join(dir, "stub_gen.go")
	require.NoError(t, run(filepath.Join("..", "local.go"), rpc, stub))
	for _, p := range []string{rpc, stub} {
		data, err := os.ReadFile(p)
		require.NoError(t, err)
		require.True(t, strings.HasPrefix(string(data), "// Code generated by internal/api/gen"))
	}
	require.Error(t, run(filepath.Join(dir, "missing.go"), rpc, stub))
}

const okSrc = `package api

import (
	"context"
	"time"
)

type Local interface {
	Ping(ctx context.Context) error
	Get(ctx context.Context, id, name string, d time.Duration) (map[string][]*Item, error)
	Watch(ctx context.Context, q Query, emit func(LogLine) error) error
	Apply(ctx context.Context, progress func(Step)) ([2]int, error)
}
`

func TestGenerateSmallInterface(t *testing.T) {
	rpc, stub, err := Generate([]byte(okSrc))
	require.NoError(t, err)
	r, s := string(rpc), string(stub)
	require.Contains(t, r, `c.call(ctx, "Ping", nil, nil)`)
	require.Contains(t, r, `c.call(ctx, "Get", []any{id, name, d}, &out)`)
	require.Contains(t, r, `c.stream(ctx, "Watch", []any{q}, nil, nil, emit)`)
	require.Contains(t, r, `c.stream(ctx, "Apply", nil, &out, progress, nil)`)
	require.Contains(t, r, `"Get": {arity: 3, stream: false`)
	require.Contains(t, r, `impl.Watch(ctx, a0, cb.Log)`)
	require.Contains(t, r, `impl.Apply(ctx, cb.Step)`)
	require.Contains(t, r, `"time"`)
	require.Contains(t, s, `GetFn func(ctx context.Context, id string, name string, d time.Duration) (map[string][]*api.Item, error)`)
	require.Contains(t, s, `WatchFn func(ctx context.Context, q api.Query, emit func(api.LogLine) error) error`)
	require.Contains(t, s, `ApplyFn func(ctx context.Context, progress func(api.Step)) ([2]int, error)`)
	require.Contains(t, s, `return zero, notImplemented("Get")`)
}

func TestGenerateErrors(t *testing.T) {
	cases := map[string]string{
		"syntax":        `package api; type Local interface {`,
		"no interface":  `package api; type Other interface{}`,
		"empty":         `package api; type Local interface{}`,
		"embedded":      `package api; type Local interface{ io.Reader }`,
		"no ctx":        `package api; type Local interface{ A(x int) error }`,
		"bad results":   `package api; import "context"; type Local interface{ A(ctx context.Context) int }`,
		"three results": `package api; import "context"; type Local interface{ A(ctx context.Context) (int, int, error) }`,
		"bad callback":  `package api; import "context"; type Local interface{ A(ctx context.Context, f func(int)) error }`,
		"two callbacks": `package api; import "context"; type Local interface{ A(ctx context.Context, p func(Step), q func(Step)) error }`,
		"reserved":      `package api; import "context"; type Local interface{ A(ctx context.Context, out int) error }`,
		"reserved ctx":  `package api; import "context"; type Local interface{ A(err context.Context) error }`,
		"unknown pkg":   `package api; import "context"; type Local interface{ A(ctx context.Context, d foo.Bar) error }`,
		"duplicate":     `package api; import "context"; type Local interface{ A(ctx context.Context) error; A(ctx context.Context) error }`,
	}
	for name, src := range cases {
		t.Run(name, func(t *testing.T) {
			_, _, err := Generate([]byte(src))
			require.Error(t, err)
		})
	}
}

func TestUnnamedParams(t *testing.T) {
	src := `package api
import "context"
type Local interface{ A(context.Context, string, int) (string, error) }`
	rpc, stub, err := Generate([]byte(src))
	require.NoError(t, err)
	require.Contains(t, string(rpc), `[]any{p1, p2}`)
	require.Contains(t, string(stub), `AFn func(p0 context.Context, p1 string, p2 int) (string, error)`)
}
