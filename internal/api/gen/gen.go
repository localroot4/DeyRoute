// header marks both outputs as generated (golangci-lint skips them).
const header = "// Code generated by internal/api/gen from local.go; DO NOT EDIT.\n\n"

// apiImportPath is the import path of package api (used by the stub).
const apiImportPath = "github.com/localroot4/deyroute/internal/api"

// Callback kinds recognised in Local method signatures.
const (
	cbNone = ""
	cbStep = "step" // progress func(Step)
	cbLog  = "log"  // emit func(LogLine) error
)

// param is one non-context parameter of a Local method.
type param struct {
	Name     string
	Type     ast.Expr
	Callback string // cbNone for a wire argument
}

// method is one Local method.
type method struct {
	Name   string
	Ctx    string   // name of the context parameter
	Params []param  // every parameter after ctx, in order
	Result ast.Expr // nil when the method returns only error
}

// wireArgs returns the parameters that travel in the JSON array.
func (m method) wireArgs() []param {
	var out []param
	for _, p := range m.Params {
		if p.Callback == cbNone {
			out = append(out, p)
		}
	}
	return out
}

// callback returns the callback parameter, if any.
func (m method) callback() (param, bool) {
	for _, p := range m.Params {
		if p.Callback != cbNone {
			return p, true
		}
	}
	return param{}, false
}

// parsed is the result of reading local.go.
type parsed struct {
	methods []method
	imports map[string]string // package name -> import path
}

// Generate parses the source of local.go and returns the contents of
// rpc_gen.go (package api) and apitest/stub_gen.go (package apitest).
func Generate(src []byte) (rpc, stub []byte, err error) {
	p, err := parseLocal(src)
	if err != nil {
		return nil, nil, err
	}
	rpc, err = emitRPC(p)
	if err != nil {
		return nil, nil, err
	}
	stub, err = emitStub(p)
	if err != nil {
		return nil, nil, err
	}
	return rpc, stub, nil
}

func parseLocal(src []byte) (*parsed, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "local.go", src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse local.go: %w", err)
	}
	p := &parsed{imports: map[string]string{}}
	for _, imp := range f.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return nil, fmt.Errorf("import %s: %w", imp.Path.Value, err)
		}
		name := path[strings.LastIndex(path, "/")+1:]
		if imp.Name != nil {
			name = imp.Name.Name
		}
		p.imports[name] = path
	}
	var iface *ast.InterfaceType
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "Local" {
			return true
		}
		if it, ok := ts.Type.(*ast.InterfaceType); ok {
			iface = it
		}
		return false
	})
	if iface == nil {
		return nil, fmt.Errorf("local.go: interface Local not found")
	}
	seen := map[string]bool{}
	for _, field := range iface.Methods.List {
		ft, ok := field.Type.(*ast.FuncType)
		if !ok || len(field.Names) != 1 {
			return nil, fmt.Errorf("local.go: Local must contain only plain methods (embedded interfaces are not supported)")
		}
		m, err := parseMethod(field.Names[0].Name, ft)
		if err != nil {
			return nil, err
		}
		if seen[m.Name] {
			return nil, fmt.Errorf("local.go: duplicate method %s", m.Name)
		}
		seen[m.Name] = true
		p.methods = append(p.methods, m)
	}
	if len(p.methods) == 0 {
		return nil, fmt.Errorf("local.go: interface Local has no methods")
	}
	return p, nil
}

// reserved are identifiers the generated code uses next to the parameters.
var reserved = map[string]bool{"c": true, "s": true, "out": true, "err": true, "zero": true, "args": true, "cb": true}

func parseMethod(name string, ft *ast.FuncType) (method, error) {
	m := method{Name: name}
	var all []param
	idx := 0
	for _, f := range ft.Params.List {
		names := f.Names
		if len(names) == 0 {
			names = []*ast.Ident{ast.NewIdent(fmt.Sprintf("p%d", idx))}
		}
		for _, n := range names {
			all = append(all, param{Name: n.Name, Type: f.Type})
			idx++
		}
	}
	if len(all) == 0 || exprString(all[0].Type) != "context.Context" {
		return m, fmt.Errorf("local.go: %s: the first parameter must be context.Context", name)
	}
	m.Ctx = all[0].Name
	callbacks := 0
	for _, p := range all[1:] {
		if reserved[p.Name] {
			return m, fmt.Errorf("local.go: %s: parameter name %q is reserved by the generator", name, p.Name)
		}
		if fn, ok := p.Type.(*ast.FuncType); ok {
			kind, err := callbackKind(fn)
			if err != nil {
				return m, fmt.Errorf("local.go: %s: parameter %s: %w", name, p.Name, err)
			}
			p.Callback = kind
			callbacks++
		}
		m.Params = append(m.Params, p)
	}
	if reserved[m.Ctx] {
		return m, fmt.Errorf("local.go: %s: parameter name %q is reserved by the generator", name, m.Ctx)
	}
	if callbacks > 1 {
		return m, fmt.Errorf("local.go: %s: at most one callback parameter is supported", name)
	}
	var results []ast.Expr
	if ft.Results != nil {
		for _, f := range ft.Results.List {
			n := len(f.Names)
			if n == 0 {
				n = 1
			}
			for i := 0; i < n; i++ {
				results = append(results, f.Type)
			}
		}
	}
	switch {
	case len(results) == 1 && exprString(results[0]) == "error":
	case len(results) == 2 && exprString(results[1]) == "error":
		m.Result = results[0]
	default:
		return m, fmt.Errorf("local.go: %s: results must be (error) or (T, error)", name)
	}
	return m, nil
}

// callbackKind recognises progress func(Step) and emit func(LogLine) error.
func callbackKind(fn *ast.FuncType) (string, error) {
	switch exprString(fn) {
	case "func(Step)":
		return cbStep, nil
	case "func(LogLine) error":
		return cbLog, nil
	}
	return "", fmt.Errorf("unsupported callback type %s (want func(Step) or func(LogLine) error)", exprString(fn))
}

// exprString prints a type expression as Go source.
func exprString(e ast.Expr) string {
	var b bytes.Buffer
	if err := printer.Fprint(&b, token.NewFileSet(), e); err != nil {
		return fmt.Sprintf("<%T>", e)
	}
	return b.String()
}

// builtinTypes are predeclared identifiers never qualified with "api.".
var builtinTypes = map[string]bool{
	"bool": true, "byte": true, "complex64": true, "complex128": true, "error": true,
	"float32": true, "float64": true, "int": true, "int8": true, "int16": true,
	"int32": true, "int64": true, "rune": true, "string": true, "uint": true,
	"uint8": true, "uint16": true, "uint32": true, "uint64": true, "uintptr": true,
	"any": true,
}

// typeString prints e; with qualify, identifiers declared in package api
// are prefixed with "api.". used collects the package selectors referenced.
func typeString(e ast.Expr, qualify bool, used map[string]bool) string {
	var b strings.Builder
	writeType(&b, e, qualify, used)
	return b.String()
}

func writeType(b *strings.Builder, e ast.Expr, qualify bool, used map[string]bool) {
	switch t := e.(type) {
	case *ast.Ident:
		if qualify && !builtinTypes[t.Name] {
			used["api"] = true
			b.WriteString("api.")
		}
		b.WriteString(t.Name)
	case *ast.SelectorExpr:
		if x, ok := t.X.(*ast.Ident); ok {
			used[x.Name] = true
		}
		b.WriteString(exprString(t))
	case *ast.StarExpr:
		b.WriteString("*")
		writeType(b, t.X, qualify, used)
	case *ast.ArrayType:
		b.WriteString("[")
		if t.Len != nil {
			b.WriteString(exprString(t.Len))
		}
		b.WriteString("]")
		writeType(b, t.Elt, qualify, used)
	case *ast.MapType:
		b.WriteString("map[")
		writeType(b, t.Key, qualify, used)
		b.WriteString("]")
		writeType(b, t.Value, qualify, used)
	case *ast.FuncType:
		b.WriteString("func(")
		if t.Params != nil {
			writeFieldTypes(b, t.Params.List, qualify, used)
		}
		b.WriteString(")")
		if t.Results != nil && len(t.Results.List) > 0 {
			b.WriteString(" ")
			multi := len(t.Results.List) > 1 || len(t.Results.List[0].Names) > 0
			if multi {
				b.WriteString("(")
			}
			writeFieldTypes(b, t.Results.List, qualify, used)
			if multi {
				b.WriteString(")")
			}
		}
	case *ast.InterfaceType:
		b.WriteString(exprString(t))
	default:
		// Unusual types (channels, inline structs) are printed verbatim.
		b.WriteString(exprString(e))
	}
}

func writeFieldTypes(b *strings.Builder, list []*ast.Field, qualify bool, used map[string]bool) {
	first := true
	for _, f := range list {
		n := len(f.Names)
		if n == 0 {
			n = 1
		}
		for i := 0; i < n; i++ {
			if !first {
				b.WriteString(", ")
			}
			first = false
			writeType(b, f.Type, qualify, used)
		}
	}
}

// signature renders "(ctx context.Context, a T, …) (R, error)".
func signature(m method, qualify bool, used map[string]bool) string {
	var b strings.Builder
	b.WriteString("(" + m.Ctx + " context.Context")
	for _, p := range m.Params {
		b.WriteString(", " + p.Name + " " + typeString(p.Type, qualify, used))
	}
	b.WriteString(")")
	if m.Result != nil {
		b.WriteString(" (" + typeString(m.Result, qualify, used) + ", error)")
	} else {
		b.WriteString(" error")
	}
	return b.String()
}

// importBlock renders the import declaration: std first, then module paths.
func importBlock(std []string, used map[string]bool, known map[string]string, self string) (string, error) {
	var local []string
	for name := range used {
		if name == self {
			continue
		}
		path, ok := known[name]
		if !ok {
			if name == "api" {
				path = apiImportPath
			} else {
				return "", fmt.Errorf("package %q used in Local but not imported by local.go", name)
			}
		}
		if strings.Contains(path, ".") {
			local = append(local, path)
		} else {
			std = append(std, path)
		}
	}
	sort.Strings(std)
	sort.Strings(local)
	std = dedupe(std)
	local = dedupe(local)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, s := range std {
		b.WriteString("\t" + strconv.Quote(s) + "\n")
	}
	if len(local) > 0 {
		b.WriteString("\n")
		for _, s := range local {
			if s == "github.com/localroot4/deyroute/internal/errors" {
				b.WriteString("\tdeyerr " + strconv.Quote(s) + "\n")
				continue
			}
			b.WriteString("\t" + strconv.Quote(s) + "\n")
		}
	}
	b.WriteString(")\n")
	return b.String(), nil
}

func dedupe(in []string) []string {
	out := in[:0]
	for i, s := range in {
		if i == 0 || s != in[i-1] {
			out = append(out, s)
		}
	}
	return out
}

func emitRPC(p *parsed) ([]byte, error) {
	used := map[string]bool{}
	var body strings.Builder

	body.WriteString("// Compile-time check that the generated client implements Local.\n")
	body.WriteString("var _ Local = (*localClient)(nil)\n\n")

	for _, m := range p.methods {
		cb, streaming := m.callback()
		fmt.Fprintf(&body, "// %s implements Local.%s by calling the daemon over the unix socket.\n", m.Name, m.Name)
		fmt.Fprintf(&body, "func (c *localClient) %s%s {\n", m.Name, signature(m, false, used))
		args := "nil"
		if wa := m.wireArgs(); len(wa) > 0 {
			names := make([]string, len(wa))
			for i, a := range wa {
				names[i] = a.Name
			}
			args = "[]any{" + strings.Join(names, ", ") + "}"
		}
		outArg := "nil"
		if m.Result != nil {
			fmt.Fprintf(&body, "\tvar out %s\n", typeString(m.Result, false, used))
			outArg = "&out"
		}
		var call string
		if streaming {
			step, logf := "nil", "nil"
			if cb.Callback == cbStep {
				step = cb.Name
			} else {
				logf = cb.Name
			}
			call = fmt.Sprintf("c.stream(%s, %q, %s, %s, %s, %s)", m.Ctx, m.Name, args, outArg, step, logf)
		} else {
			call = fmt.Sprintf("c.call(%s, %q, %s, %s)", m.Ctx, m.Name, args, outArg)
		}
		if m.Result != nil {
			fmt.Fprintf(&body, "\terr := %s\n\treturn out, err\n}\n\n", call)
		} else {
			fmt.Fprintf(&body, "\treturn %s\n}\n\n", call)
		}
	}

	body.WriteString("// NewLocalHandler returns the HTTP handler that serves impl on\n")
	body.WriteString("// POST /v1/rpc/<Method> (see ARCHITECTURE.md section 6). Panics in impl are\n")
	body.WriteString("// recovered, logged with their stack and answered with DEY-X000.\n")
	body.WriteString("func NewLocalHandler(impl Local, logger *slog.Logger) http.Handler {\n")
	body.WriteString("\treturn newRPCHandler(logger, map[string]rpcMethod{\n")
	for _, m := range p.methods {
		_, streaming := m.callback()
		wa := m.wireArgs()
		argsName, cbName := "_", "_"
		if len(wa) > 0 {
			argsName = "args"
		}
		if streaming {
			cbName = "cb"
		}
		fmt.Fprintf(&body, "\t\t%q: {arity: %d, stream: %t, call: func(ctx context.Context, %s []json.RawMessage, %s *rpcCallbacks) (any, error) {\n",
			m.Name, len(wa), streaming, argsName, cbName)
		for i, a := range wa {
			fmt.Fprintf(&body, "\t\t\tvar a%d %s\n", i, typeString(a.Type, false, used))
			fmt.Fprintf(&body, "\t\t\tif err := decodeArg(args, %d, &a%d); err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", i, i)
		}
		callArgs := []string{"ctx"}
		ai := 0
		for _, prm := range m.Params {
			if prm.Callback == cbNone {
				callArgs = append(callArgs, fmt.Sprintf("a%d", ai))
				ai++
				continue
			}
			if prm.Callback == cbStep {
				callArgs = append(callArgs, "cb.Step")
			} else {
				callArgs = append(callArgs, "cb.Log")
			}
		}
		invocation := fmt.Sprintf("impl.%s(%s)", m.Name, strings.Join(callArgs, ", "))
		if m.Result != nil {
			fmt.Fprintf(&body, "\t\t\treturn %s\n", invocation)
		} else {
			fmt.Fprintf(&body, "\t\t\treturn nil, %s\n", invocation)
		}
		body.WriteString("\t\t}},\n")
	}
	body.WriteString("\t})\n}\n")

	imports, err := importBlock([]string{"context", "encoding/json", "log/slog", "net/http"}, used, p.imports, "api")
	if err != nil {
		return nil, err
	}
	src := header + "package api\n\n" + imports + "\n" + body.String()
	return formatSource("rpc_gen.go", src)
}

func emitStub(p *parsed) ([]byte, error) {
	used := map[string]bool{"api": true}
	var body strings.Builder

	body.WriteString("// Stub implements api.Local with one optional function per method, for\n")
	body.WriteString("// CLI and TUI tests. A method whose function is nil returns DEY-X008.\n")
	body.WriteString("type Stub struct {\n")
	for _, m := range p.methods {
		fmt.Fprintf(&body, "\t// %sFn implements %s.\n", m.Name, m.Name)
		fmt.Fprintf(&body, "\t%sFn func%s\n", m.Name, signature(m, true, used))
	}
	body.WriteString("}\n\n")
	body.WriteString("// Compile-time check that Stub implements api.Local.\n")
	body.WriteString("var _ api.Local = (*Stub)(nil)\n\n")

	for _, m := range p.methods {
		names := []string{m.Ctx}
		for _, prm := range m.Params {
			names = append(names, prm.Name)
		}
		fmt.Fprintf(&body, "// %s calls %sFn or returns DEY-X008 when it is nil.\n", m.Name, m.Name)
		fmt.Fprintf(&body, "func (s *Stub) %s%s {\n", m.Name, signature(m, true, used))
		fmt.Fprintf(&body, "\tif s.%sFn == nil {\n", m.Name)
		if m.Result != nil {
			fmt.Fprintf(&body, "\t\tvar zero %s\n\t\treturn zero, notImplemented(%q)\n\t}\n", typeString(m.Result, true, used), m.Name)
		} else {
			fmt.Fprintf(&body, "\t\treturn notImplemented(%q)\n\t}\n", m.Name)
		}
		fmt.Fprintf(&body, "\treturn s.%sFn(%s)\n}\n\n", m.Name, strings.Join(names, ", "))
	}

	imports, err := importBlock([]string{"context"}, used, p.imports, "apitest")
	if err != nil {
		return nil, err
	}
	src := header + "package apitest\n\n" + imports + "\n" + body.String()
	return formatSource("apitest/stub_gen.go", src)
}

// GenerateUnimplemented parses the source of local.go and returns the
// contents of unimpl_gen.go (package api): UnimplementedLocal, a Local whose
// every method answers DEY-X009 (wrong role). A daemon embeds it and
// overrides the methods its role serves.
func GenerateUnimplemented(src []byte) ([]byte, error) {
	p, err := parseLocal(src)
	if err != nil {
		return nil, err
	}
	return emitUnimpl(p)
}

func emitUnimpl(p *parsed) ([]byte, error) {
	used := map[string]bool{}
	var body strings.Builder

	body.WriteString("// UnimplementedLocal implements Local by answering DEY-X009 (\"this command\n")
	body.WriteString("// needs a <Need>, but this server is a <Role>\") for every method. A daemon\n")
	body.WriteString("// embeds it and overrides the methods its role serves, e.g.\n")
	body.WriteString("//\n")
	body.WriteString("//\ttype nodeLocal struct{ api.UnimplementedLocal }\n")
	body.WriteString("//\n")
	body.WriteString("//\tl := &nodeLocal{UnimplementedLocal: api.UnimplementedLocal{Role: \"node\", Need: \"hub\"}}\n")
	body.WriteString("type UnimplementedLocal struct {\n")
	body.WriteString("\t// Role is the role of this server (hub or node).\n")
	body.WriteString("\tRole string\n")
	body.WriteString("\t// Need is the role the unimplemented methods require.\n")
	body.WriteString("\tNeed string\n")
	body.WriteString("}\n\n")
	body.WriteString("// Compile-time check that UnimplementedLocal implements Local.\n")
	body.WriteString("var _ Local = UnimplementedLocal{}\n\n")
	body.WriteString("// wrongRole is the DEY-X009 error every method returns.\n")
	body.WriteString("func (u UnimplementedLocal) wrongRole() error {\n")
	body.WriteString("\treturn deyerr.New(deyerr.X009, deyerr.Params{\"role\": u.Role, \"need\": u.Need})\n")
	body.WriteString("}\n\n")
	for _, m := range p.methods {
		fmt.Fprintf(&body, "// %s implements Local.%s; it returns DEY-X009.\n", m.Name, m.Name)
		fmt.Fprintf(&body, "func (u UnimplementedLocal) %s%s {\n", m.Name, signature(m, false, used))
		if m.Result != nil {
			fmt.Fprintf(&body, "\tvar zero %s\n\treturn zero, u.wrongRole()\n}\n\n", typeString(m.Result, false, used))
		} else {
			body.WriteString("\treturn u.wrongRole()\n}\n\n")
		}
	}
	known := map[string]string{"deyerr": "github.com/localroot4/deyroute/internal/errors"}
	for k, v := range p.imports {
		known[k] = v
	}
	used["deyerr"] = true
	imports, err := importBlock([]string{"context"}, used, known, "api")
	if err != nil {
		return nil, err
	}
	src := header + "package api\n\n" + imports + "\n" + body.String()
	return formatSource("unimpl_gen.go", src)
}

func formatSource(name, src string) ([]byte, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("format %s: %w\n%s", name, err, src)
	}
	return out, nil
}
